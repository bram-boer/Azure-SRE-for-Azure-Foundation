"""Compose STARTERKIT.md, the single-page playbook, from the source Markdown files.

Run from the repository root: python tools/build-playbook.py
"""
import posixpath
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = "STARTERKIT.md"
SECTIONS = [
    ("overview", "Overview", "README.md"),
    ("topology", "Agent topology", "agent-topology.md"),
    ("setup", "Setup guide", "setup-guide.md"),
    ("use-cases", "Use cases", "use-cases.md"),
    ("waf", "WAF pillar use cases", "waf-pillar-use-cases.md"),
    ("demo", "Demo guide", "demo-guide.md"),
    ("costs", "Costs", "costs.md"),
    ("infra", "Infrastructure guidance", "infra/README.md"),
    ("deploy", "Reference deployment", "infra/sre-agent/README.md"),
    ("verification", "Verification", "verification.md"),
]
SECTION_BY_FILE = {path: anchor for anchor, _, path in SECTIONS}
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)\)")
FENCE = re.compile(r"^\s*(```|~~~)")


def rewrite_link(target: str, source: str) -> str:
    if re.match(r"^[a-z]+:", target) or target.startswith("#"):
        return target
    path, _, fragment = target.replace("\\", "/").partition("#")
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved == OUTPUT:
        return f"#{fragment}" if fragment else "#overview"
    if resolved in SECTION_BY_FILE:
        return f"#{fragment}" if fragment else f"#{SECTION_BY_FILE[resolved]}"
    return resolved + (f"#{fragment}" if fragment else "")


def transform(text: str, source: str) -> str:
    lines, in_fence = [], False
    for line in text.splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence:
            if line.startswith("#"):
                line = "#" + line
            line = LINK.sub(lambda m: f"[{m.group(1)}]({rewrite_link(m.group(2), source)})", line)
        lines.append(line)
    return "\n".join(lines).strip()


def slug(heading: str) -> str:
    heading = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    heading = re.sub(r"[`*]|<[^>]+>", "", heading).strip().lower()
    return re.sub(r"[^\w\- ]", "", heading).replace(" ", "-")


def check_anchors(document: str) -> list[str]:
    anchors, seen, in_fence = set(re.findall(r'<a id="([^"]+)"></a>', document)), Counter(), False
    for line in document.splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and (match := re.match(r"^#{1,6}\s+(.*)", line)):
            base = slug(match.group(1))
            anchors.add(base if not seen[base] else f"{base}-{seen[base]}")
            seen[base] += 1
    links = {target[1:] for _, target in LINK.findall(document) if target.startswith("#")}
    return sorted(link for link in links if link not in anchors)


def main() -> None:
    parts = [
        "# Azure SRE Agent - Foundation Starter Kit",
        "",
        "> Generated by `tools/build-playbook.py` from the source Markdown files. Edit the sources, not this file.",
        "",
        "## Contents",
        "",
        *[f"- [{title}](#{anchor}) (source: [`{path}`]({path}))" for anchor, title, path in SECTIONS],
    ]
    for anchor, _, path in SECTIONS:
        body = transform((ROOT / path).read_text(encoding="utf-8"), path)
        parts += ["", "---", "", f'<a id="{anchor}"></a>', "", body]
    document = "\n".join(parts) + "\n"
    broken = check_anchors(document)
    if broken:
        raise SystemExit(f"Broken in-page anchors: {broken}")
    missing = [
        target for _, target in LINK.findall(document)
        if not re.match(r"^([a-z]+:|#)", target) and not (ROOT / target.split("#")[0]).exists()
    ]
    if missing:
        raise SystemExit(f"Broken relative links: {sorted(set(missing))}")
    (ROOT / OUTPUT).write_text(document, encoding="utf-8")
    print(f"{OUTPUT}: {len(SECTIONS)} sections, {len(document.splitlines())} lines, anchors OK")


if __name__ == "__main__":
    main()
